<?php

namespace App\Modules\Profesionales\Http\Requests\Directorio;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Cambio de estado del profesional (03/RF-D07 / 03/RN-20).
 */
final class ChangeProfesionalStatusRequest extends FormRequest
{
    public function authorize(): bool
    {
        return true;
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            'motivo' => ['required', 'string', 'max:1000'],
            'version' => ['required', 'integer', 'min:1'],
        ];
    }

    /**
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'motivo.required' => 'El motivo es obligatorio para cambiar el estado del profesional.',
            'motivo.max' => 'El motivo no puede superar los 1000 caracteres.',
            'version.required' => 'La versión del registro es obligatoria.',
        ];
    }
}
